/// Standard spacing and radius values for consistent layouts.
abstract final class AppSpacing {
  /// Extra-small layout gap.
  static const xs = 4.0;

  /// Small layout gap.
  static const sm = 8.0;

  /// Medium layout gap.
  static const md = 16.0;

  /// Large layout gap.
  static const lg = 24.0;

  /// Extra-large layout gap.
  static const xl = 32.0;
}

/// Standard corner radii for product components.
abstract final class AppRadii {
  /// Input control radius.
  static const input = 12.0;

  /// Card radius.
  static const card = 16.0;

  /// Prominent feature-surface radius.
  static const feature = 24.0;
}
